// Builds src/data/nodeAnchors.js: per dataset, which final node each V1 node
// became. Node ids cannot be compared across versions: V1 ids come from the
// Master ID column, final ids from the Node Mapping Index, and several V1 nodes
// may merge into one final node. The `key` field (V1_84, V2_25) is the reliable
// identifier, and "Node Mapping.csv" is the source of truth linking the two.
//
//   node scripts/build-node-anchors.mjs           regenerate the file
//   node scripts/build-node-anchors.mjs --check   fail if the file is stale
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mappingPath = path.join(root, "public/new data/CLD data - Node Mapping.csv");
const dataPath = path.join(root, "src/data/new_data.js");
const outputPath = path.join(root, "src/data/nodeAnchors.js");

// The mapping names these V2 targets but its id lookup returned #N/A because
// the name is misspelled ("Data retained by private entites").
const MISSING_ID_FIXES = { V1_4: "V2_11", V1_5: "V2_11" };

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        cell += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(cell);
      cell = "";
    } else if (ch === "\n") {
      rows.push([...row, cell.replace(/\r$/, "")]);
      row = [];
      cell = "";
    } else cell += ch;
  }
  if (cell || row.length) rows.push([...row, cell]);
  return rows;
}

function loadMapping() {
  const text = fs.readFileSync(mappingPath, "utf8").replace(/^﻿/, "");
  const v1ToV2 = new Map();
  for (const row of parseCsv(text).slice(1)) {
    const v1 = row[1]?.trim();
    const v2 = row[3]?.trim();
    if (!v1) continue;
    const target = v2 && v2 !== "#N/A" ? v2 : MISSING_ID_FIXES[v1];
    if (target) v1ToV2.set(v1, target);
  }
  return v1ToV2;
}

function loadDatasets() {
  const source = fs
    .readFileSync(dataPath, "utf8")
    .replace(/export\s*\{[^}]*\};?/, "");
  return new Function(`${source};return allCyDataSets;`)();
}

function buildAnchors(datasets, v1ToV2) {
  const anchors = {};
  const report = [];
  for (const [name, versions] of Object.entries(datasets)) {
    const finalIdByKey = new Map(
      versions.final.nodes.map(({ data }) => [data.key, data.id])
    );
    anchors[name] = {};
    const unanchored = [];
    for (const { data } of versions.V1.nodes) {
      const finalId = finalIdByKey.get(v1ToV2.get(data.key));
      if (finalId === undefined) unanchored.push(data.key);
      else anchors[name][data.id] = finalId;
    }
    report.push({
      name,
      anchored: Object.keys(anchors[name]).length,
      total: versions.V1.nodes.length,
      unanchored,
    });
  }
  return { anchors, report };
}

const { anchors, report } = buildAnchors(loadDatasets(), loadMapping());
const output =
  "// Generated by scripts/build-node-anchors.mjs. Do not edit by hand.\n" +
  `export const nodeAnchors = ${JSON.stringify(anchors, null, 2)};\n`;

for (const { name, anchored, total, unanchored } of report) {
  console.log(
    `${name}: ${anchored}/${total} V1 nodes anchored` +
      (unanchored.length ? ` (no final node: ${unanchored.join(", ")})` : "")
  );
}

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath)
    ? fs.readFileSync(outputPath, "utf8")
    : "";
  if (current !== output) {
    console.error("src/data/nodeAnchors.js is stale: run npm run anchors");
    process.exit(1);
  }
  console.log("src/data/nodeAnchors.js is up to date");
} else {
  fs.writeFileSync(outputPath, output);
}
